//! Mesh export (the OBJ writer and XYZ point clouds).

use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::Path;

use anyhow::Result;
use nerthus_core::TerrainDefinition;

/// Units for mesh output (`I` argument of `KC`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MeshUnits {
    /// Unit-sized mesh, heights scaled by height/scale.
    Normalized,
    /// Metres from the terrain definition.
    Meters,
    /// Kilometres.
    Kilometers,
}

/// Options of the OBJ export.
#[derive(Clone, Copy, Debug)]
pub struct ObjOptions {
    pub quads: bool,
    pub units: MeshUnits,
    pub centered: bool,
    /// Zero the border vertices (skirt-free, flat edges).
    pub zero_edges: bool,
    pub skip_uvs: bool,
    pub offset_x: f32,
    pub offset_z: f32,
}

impl Default for ObjOptions {
    fn default() -> Self {
        Self {
            quads: false,
            units: MeshUnits::Meters,
            centered: true,
            zero_edges: false,
            skip_uvs: false,
            offset_x: 0.0,
            offset_z: 0.0,
        }
    }
}

/// Writes a heightfield grid as an OBJ mesh. `heights` is row-major (`size x size`).
pub fn write_obj(path: &Path, heights: &[f32], size: usize, definition: &TerrainDefinition, options: &ObjOptions) -> Result<()> {
    let mut grid = heights.to_vec();
    if options.zero_edges {
        for i in 0..size {
            grid[i] = 0.0;
            grid[(size - 1) * size + i] = 0.0;
            grid[i * size] = 0.0;
            grid[i * size + size - 1] = 0.0;
        }
    } else {
        // Column 1 is copied into column 0 (S[0, j] = S[1, j]).
        for j in 0..size {
            grid[j * size] = grid[j * size + 1];
        }
    }
    let (horizontal, vertical) = match options.units {
        MeshUnits::Normalized => (1.0, definition.height / definition.scale),
        MeshUnits::Meters => (definition.scale, definition.height),
        MeshUnits::Kilometers => (definition.scale * 0.001, definition.height * 0.001),
    };
    let origin_x = if options.centered { (size as f32 - 1.0) / -2.0 + options.offset_x } else { options.offset_x };
    let origin_z = if options.centered { (size as f32 - 1.0) / 2.0 + options.offset_z } else { options.offset_z };
    let denominator = size as f32 - 1.0;

    let mut writer = BufWriter::new(File::create(path)?);
    writeln!(writer, "# Generated by Nerthus")?;
    let name = path.file_stem().and_then(|stem| stem.to_str()).unwrap_or("terrain");
    writeln!(writer, "g {name}")?;
    for row in 0..size {
        for column in 0..size {
            // The grid is indexed [column, row] and emitted row by row.
            let x = (origin_x + column as f32) / denominator * horizontal;
            let y = grid[row * size + column] * vertical;
            let z = (origin_z - row as f32) / denominator * horizontal;
            writeln!(writer, "v {x} {y} {z}")?;
            if !options.skip_uvs {
                let u = column as f32 / denominator;
                let v = row as f32 / denominator;
                writeln!(writer, "vt {u} {v}")?;
            }
        }
    }
    let mut index = 0usize;
    for row in 0..size {
        for column in 0..size {
            if column < size - 1 && row < size - 1 {
                if options.quads {
                    let a = index + size + 1;
                    let b = index + 1;
                    let c = index + 2;
                    let d = index + size + 2;
                    writeln!(writer, "f {a}/{a} {b}/{b} {c}/{c} {d}/{d}")?;
                } else {
                    let a = index + 1;
                    let b = index + size + 2;
                    let c = index + size + 1;
                    let d = index + size + 2;
                    let e = index + 1;
                    let f = index + 2;
                    writeln!(writer, "f {a}/{a} {b}/{b} {c}/{c}")?;
                    writeln!(writer, "f {d}/{d} {e}/{e} {f}/{f}")?;
                }
            }
            index += 1;
        }
    }
    writer.flush()?;
    Ok(())
}

/// Writes an XYZ point cloud.
pub fn write_xyz(path: &Path, heights: &[f32], size: usize, definition: &TerrainDefinition, units: MeshUnits, skip_zero: bool) -> Result<()> {
    let (scale, height) = match units {
        MeshUnits::Normalized => ((size as f32 - 1.0) / -2.0, 1.0),
        MeshUnits::Meters => (size as f32 / definition.scale, definition.height),
        MeshUnits::Kilometers => (size as f32 / definition.scale * 0.01, definition.height * 0.01),
    };
    let origin_x = (size as f32 - 1.0) / -2.0;
    let origin_z = (size as f32 - 1.0) / 2.0;
    let mut writer = BufWriter::new(File::create(path)?);
    for row in 0..size {
        for column in 0..size {
            let value = heights[row * size + column];
            if skip_zero && value == 0.0 {
                continue;
            }
            let x = (origin_x + column as f32) / scale;
            let y = value * height;
            let z = (origin_z - row as f32) / scale;
            writeln!(writer, "{x} {y} {z}")?;
        }
    }
    writer.flush()?;
    Ok(())
}

/// MeshOutput's file formats.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MeshFormat {
    Obj,
    Xyz,
    /// Written as the OBJ (no FBX converter is run).
    Fbx,
}

impl MeshFormat {
    pub fn from_index(index: i32) -> Self {
        match index {
            1 => MeshFormat::Xyz,
            2 => MeshFormat::Fbx,
            _ => MeshFormat::Obj,
        }
    }
}

/// Mesh topology (`Structure`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MeshStructure {
    Tris,
    Quads,
    /// RTIN simplification ("Sophia").
    Adaptive,
}

impl MeshStructure {
    pub fn from_index(index: i32) -> Self {
        match index {
            1 => MeshStructure::Quads,
            2 => MeshStructure::Adaptive,
            _ => MeshStructure::Tris,
        }
    }
}

impl MeshUnits {
    pub fn from_index(index: i32) -> Self {
        match index {
            1 => MeshUnits::Meters,
            2 => MeshUnits::Kilometers,
            _ => MeshUnits::Normalized,
        }
    }
}

/// The MeshOutput node's settings.
#[derive(Clone, Debug)]
pub struct MeshExport {
    pub format: MeshFormat,
    pub structure: MeshStructure,
    pub units: MeshUnits,
    pub vertex_count: usize,
    pub texture_coords: bool,
    pub walls: bool,
    /// Number of files: the mesh plus LODs, each with half the vertices.
    pub levels: usize,
}

/// MeshOutput's grid preparation: resized to `vertices + 1`, rotated by
/// 180 degrees and mirrored back (which leaves the last row and column
/// alone), then the borders copy their neighbours.
fn mesh_grid(heights: &[f32], vertices: usize) -> (Vec<f32>, usize) {
    let side = vertices + 1;
    let image = nerthus_image::Image::from_gray(heights);
    let mut resized = nerthus_image::resize::resize(&image, side, side);
    resized.to_linear_gray();
    let source = resized.data;
    let mut grid = vec![0.0f32; side * side];
    for y in 0..side {
        for x in 0..side {
            let flipped_row = side - 1 - y;
            let value = if x + 2 <= side && y + 2 <= side { source[flipped_row * side + x] } else { source[flipped_row * side + (side - 1 - x)] };
            grid[y * side + x] = value;
        }
    }
    for index in 0..side {
        grid[index] = grid[side + index];
        grid[(side - 1) * side + index] = grid[(side - 2) * side + index];
        grid[index * side] = grid[index * side + 1];
        grid[index * side + side - 1] = grid[index * side + side - 2];
    }
    (grid, side)
}

/// `name` with `suffix` inserted before the extension (`_LOD1` etc.).
fn with_suffix(path: &Path, suffix: &str, extension: &str) -> std::path::PathBuf {
    let stem = path.file_name().and_then(|name| name.to_str()).unwrap_or("mesh");
    path.with_file_name(format!("{stem}{suffix}.{extension}"))
}

/// `MeshOutput`: writes the mesh (and its LODs) for `heights`, already
/// mapped through the build range. `base` is the path without extension.
pub fn export_mesh(base: &Path, heights: &[f32], size: usize, settings: &MeshExport, definition: &TerrainDefinition) -> Result<Vec<std::path::PathBuf>> {
    let mut written = Vec::new();
    if settings.structure == MeshStructure::Adaptive && settings.format == MeshFormat::Obj {
        let mut target = settings.vertex_count * settings.vertex_count;
        target = target.min(size * size);
        for _ in 0..settings.levels {
            target /= 2;
        }
        let mut rtin = Rtin::new(heights, size, target as i32);
        rtin.compute_errors();
        for level in (0..settings.levels).rev() {
            let suffix = if level == 0 { String::new() } else { format!("_LOD{level}") };
            let path = with_suffix(base, &suffix, "obj");
            rtin.optimize();
            rtin.write_obj(&path, settings.units, definition)?;
            written.push(path);
            rtin.target_polycount *= 2;
        }
        return Ok(written);
    }
    let mut vertices = settings.vertex_count;
    for level in 0..settings.levels {
        let suffix = if level == 0 { String::new() } else { format!("_LOD{level}") };
        let (grid, side) = mesh_grid(heights, vertices);
        match settings.format {
            MeshFormat::Xyz => {
                let path = with_suffix(base, &suffix, "xyz");
                write_xyz(&path, &grid, side, definition, settings.units, true)?;
                written.push(path);
            }
            MeshFormat::Obj | MeshFormat::Fbx => {
                let path = with_suffix(base, &suffix, "obj");
                let options = ObjOptions {
                    quads: settings.structure == MeshStructure::Quads,
                    units: settings.units,
                    centered: true,
                    zero_edges: settings.walls,
                    skip_uvs: !settings.texture_coords,
                    offset_x: 0.0,
                    offset_z: 0.0,
                };
                write_obj(&path, &grid, side, definition, &options)?;
                written.push(path);
            }
        }
        vertices /= 2;
    }
    Ok(written)
}

/// The adaptive mesher ("Sophia"): a right-triangulated
/// irregular network refined until the error threshold yields the target
/// polygon count.
struct Rtin {
    /// `C`: grid size in cells.
    cells: usize,
    /// `S`: grid size in vertices (`cells + 1`).
    side: usize,
    heights: Vec<f32>,
    errors: Vec<f32>,
    indices: Vec<i32>,
    vertices: Vec<i32>,
    triangles: Vec<i32>,
    vertex_count: i32,
    triangle_count: i32,
    written_triangles: usize,
    max_error: f32,
    safety_threshold: f32,
    optimization_threshold: i32,
    accuracy: f32,
    finder_accuracy: f32,
    target_polycount: i32,
}

impl Rtin {
    /// Pads the map to `(n + 1)^2` by repeating the
    /// last row and column.
    fn new(heights: &[f32], size: usize, target: i32) -> Self {
        let side = size + 1;
        let mut padded = vec![0.0f32; side * side];
        for row in 0..size {
            padded[row * side..row * side + size].copy_from_slice(&heights[row * size..(row + 1) * size]);
        }
        for column in 0..side {
            padded[side * (side - 1) + column] = padded[side * (side - 2) + column];
        }
        for row in 0..side {
            padded[side * row + side - 1] = padded[side * row + side - 2];
        }
        Self {
            cells: size,
            side,
            heights: padded,
            errors: Vec::new(),
            indices: Vec::new(),
            vertices: Vec::new(),
            triangles: Vec::new(),
            vertex_count: 0,
            triangle_count: 0,
            written_triangles: 0,
            max_error: 1.0,
            safety_threshold: 1e-8,
            optimization_threshold: 1000,
            accuracy: 0.9,
            finder_accuracy: 0.9,
            target_polycount: target,
        }
    }

    /// The error each midpoint adds, propagated up the triangle
    /// hierarchy.
    fn compute_errors(&mut self) {
        let size = self.cells as i32;
        let side = self.side;
        self.errors = vec![0.0f32; side * side];
        self.indices = vec![0; side * side];
        let triangle_total = (size * size * 2 - 2) as usize;
        let leaf_start = triangle_total - (size * size) as usize;
        let mut corners = vec![0i32; triangle_total * 4];
        for triangle in 0..triangle_total {
            let mut id = triangle as i32 + 2;
            let (mut ax, mut ay, mut bx, mut by, mut cx, mut cy) = (0, 0, 0, 0, 0, 0);
            if id & 1 == 1 {
                bx = size;
                by = size;
                cx = size;
            } else {
                ax = size;
                ay = size;
                cy = size;
            }
            loop {
                id >>= 1;
                if id <= 1 {
                    break;
                }
                let mx = (ax + bx) >> 1;
                let my = (ay + by) >> 1;
                if id & 1 == 1 {
                    bx = ax;
                    by = ay;
                    ax = cx;
                    ay = cy;
                } else {
                    ax = bx;
                    ay = by;
                    bx = cx;
                    by = cy;
                }
                cx = mx;
                cy = my;
            }
            let at = triangle * 4;
            corners[at] = ax;
            corners[at + 1] = ay;
            corners[at + 2] = bx;
            corners[at + 3] = by;
        }
        let at = |x: i32, y: i32| y as usize * side + x as usize;
        for triangle in (0..triangle_total).rev() {
            let base = triangle * 4;
            let (ax, ay, bx, by) = (corners[base], corners[base + 1], corners[base + 2], corners[base + 3]);
            let mx = (ax + bx) >> 1;
            let my = (ay + by) >> 1;
            let cx = mx + my - ay;
            let cy = my + ax - mx;
            let interpolated = (self.heights[at(ax, ay)] + self.heights[at(bx, by)]) / 2.0;
            let middle = at(mx, my);
            let error = (interpolated - self.heights[middle]).abs();
            self.errors[middle] = self.errors[middle].max(error);
            if triangle < leaf_start {
                let left = at((ax + cx) >> 1, (ay + cy) >> 1);
                let right = at((bx + cx) >> 1, (by + cy) >> 1);
                self.errors[middle] = self.errors[middle].max(self.errors[right]).max(self.errors[left]);
            }
        }
    }

    fn reset(&mut self) {
        self.vertices.clear();
        self.triangles.clear();
        self.vertex_count = 0;
        self.triangle_count = 0;
        self.written_triangles = 0;
    }

    fn splits(&self, ax: i32, ay: i32, cx: i32, cy: i32, mx: i32, my: i32) -> bool {
        (ax - cx).abs() + (ay - cy).abs() > 1 && self.errors[my as usize * self.side + mx as usize] > self.max_error
    }

    /// Counts the vertices and triangles of the current mesh.
    fn count(&mut self, ax: i32, ay: i32, bx: i32, by: i32, cx: i32, cy: i32) {
        let mx = (ax + bx) >> 1;
        let my = (ay + by) >> 1;
        if self.splits(ax, ay, cx, cy, mx, my) {
            self.count(cx, cy, ax, ay, mx, my);
            self.count(bx, by, cx, cy, mx, my);
            return;
        }
        for (x, y) in [(ax, ay), (bx, by), (cx, cy)] {
            let index = y as usize * self.side + x as usize;
            if self.indices[index] == 0 {
                self.vertex_count += 1;
                self.indices[index] = self.vertex_count;
            }
        }
        self.triangle_count += 1;
    }

    /// Emits the vertices and triangles counted by `count`.
    fn emit(&mut self, ax: i32, ay: i32, bx: i32, by: i32, cx: i32, cy: i32) {
        let mx = (ax + bx) >> 1;
        let my = (ay + by) >> 1;
        if self.splits(ax, ay, cx, cy, mx, my) {
            self.emit(cx, cy, ax, ay, mx, my);
            self.emit(bx, by, cx, cy, mx, my);
            return;
        }
        for (x, y) in [(ax, ay), (bx, by), (cx, cy)] {
            let vertex = (self.indices[y as usize * self.side + x as usize] - 1) as usize;
            self.vertices[2 * vertex] = x;
            self.vertices[2 * vertex + 1] = y;
            self.triangles[self.written_triangles] = vertex as i32;
            self.written_triangles += 1;
        }
    }

    /// Builds the mesh for the current error threshold.
    fn build(&mut self) {
        self.indices.iter_mut().for_each(|index| *index = 0);
        let size = self.cells as i32;
        self.count(0, 0, size, size, size, 0);
        self.count(size, size, 0, 0, 0, size);
        self.vertices = vec![0; self.vertex_count as usize * 2];
        self.triangles = vec![0; self.triangle_count as usize * 3];
        self.written_triangles = 0;
        self.emit(0, 0, size, size, size, 0);
        self.emit(size, size, 0, 0, 0, size);
    }

    /// Lowers the threshold until the mesh has enough vertices.
    fn find_threshold(&mut self, target: i32) {
        let half = target / 2;
        let mut last = 1.0f32;
        while self.max_error > self.safety_threshold {
            if self.max_error == 0.0 {
                self.max_error = last;
                break;
            }
            self.build();
            if (self.vertices.len() as i32) < half {
                last = self.max_error;
                self.max_error *= self.finder_accuracy;
                self.reset();
                continue;
            }
            break;
        }
    }

    /// Share of cells whose (oddly signed) neighbourhood mean is
    /// within 1e-7 of their height.
    fn flat_fraction(&self) -> f32 {
        let side = self.side;
        let mut flat = 0usize;
        for row in 0..side {
            let above = row.saturating_sub(1);
            let below = (row + 1).min(side - 1);
            for column in 0..side {
                let left = column.saturating_sub(1);
                let right = (column + 1).min(side - 1);
                let h = |x: usize, y: usize| self.heights[y * side + x];
                let sum = h(left, above) + h(column, above) + h(right, above) + h(left, row) + h(right, row) + h(left, below) + h(column, below) + h(right, below);
                if sum.abs() * 0.125 - h(column, row) < 1e-7 {
                    flat += 1;
                }
            }
        }
        flat as f32 / (side * side) as f32
    }

    /// Tunes the error threshold towards the target polygon count.
    fn optimize(&mut self) {
        let mut target = self.target_polycount.min(((self.cells - 1) * (self.cells - 1)) as i32);
        loop {
            self.find_threshold(target);
            self.reset();
            let mut loops = 0;
            loop {
                loops += 1;
                self.build();
                if self.vertices.len() as i32 >= target || loops > self.optimization_threshold {
                    break;
                }
                self.max_error *= self.accuracy;
                self.reset();
            }
            if loops < self.optimization_threshold {
                break;
            }
            target = (target as f32 * (1.0 - self.flat_fraction())) as i32;
        }
    }

    /// Writes the mesh as OBJ.
    fn write_obj(&self, path: &Path, units: MeshUnits, definition: &TerrainDefinition) -> Result<()> {
        let (horizontal, vertical) = match units {
            MeshUnits::Normalized => (1.0f32, definition.height / definition.scale),
            MeshUnits::Meters => (definition.scale, definition.height),
            MeshUnits::Kilometers => (definition.scale * 0.001, definition.height * 0.001),
        };
        let reciprocal = 1.0 / self.side as f32;
        let mut writer = BufWriter::new(File::create(path)?);
        writeln!(writer, "# Generated by Nerthus")?;
        let name = path.file_stem().and_then(|stem| stem.to_str()).unwrap_or("terrain");
        writeln!(writer, "g {name}")?;
        for vertex in self.vertices.chunks(2) {
            let x = (vertex[0] as f32 * reciprocal - 0.5) * horizontal;
            let y = (vertex[1] as f32 * reciprocal - 0.5) * horizontal;
            let height = self.heights[vertex[1] as usize * self.side + vertex[0] as usize] * vertical;
            writeln!(writer, "v {x} {height} {y}")?;
        }
        for vertex in self.vertices.chunks(2) {
            let u = vertex[0] as f32 * reciprocal;
            let v = 1.0 - vertex[1] as f32 * reciprocal;
            writeln!(writer, "vt {u} {v}")?;
        }
        for triangle in self.triangles.chunks(3) {
            let (a, b, c) = (triangle[0] + 1, triangle[1] + 1, triangle[2] + 1);
            writeln!(writer, "f {a}/{a} {b}/{b} {c}/{c}")?;
        }
        writer.flush()?;
        Ok(())
    }
}
